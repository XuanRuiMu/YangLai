export function 取道具(id) {
  return 配置.道具.find((项) => 项.id === id) || null;
}

export function 取灯光预设(名) {
  return 配置.灯光预设[名] || 配置.灯光预设.舞台;
}

export function 取灯光预设列表() {
  return Object.keys(配置.灯光预设).map((k) => 配置.灯光预设[k]);
}

export function 取称号(好感) {
  const 表 = 配置.好感度.等级表;
  let 命中 = 表[0];
  for (const 档 of 表) if (好感 >= 档.阈值) 命中 = 档;
  return 命中.称号;
}

export function 取画质等级(平均帧率) {
  const 阶梯 = 配置.画质.阶梯;
  return 阶梯.find((档) => 平均帧率 >= 档.最低帧率) || 阶梯[阶梯.length - 1];
}

export function 随机取(数组) {
  return 数组[Math.floor(Math.random() * 数组.length)];
}
